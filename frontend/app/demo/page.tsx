import JobPostCardItem from "@/components/Dashboard/JobPostCardItem";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { Card, CardContent } from "@/components/ui/card";
import { JobPostInfo, MatchDetails } from "@/utils/supabase/types/types";
import demoReport from "@/lib/demo/demo-report.json";
import { ArrowLeftIcon } from "lucide-react";
import type { Metadata } from "next";
import Link from "next/link";

export const metadata: Metadata = {
  title: "Sample report | Resumatcher",
  description: "A real Resumatcher report: job posts matched to a sample CV, with scores and explanations.",
};

// Static report generated by the backend for a sample CV: always available, no login, no AI quota used
type DemoJob = { jobPost: JobPostInfo; matchScore: number; matchDetails: MatchDetails };

function DemoReport() {
  const { candidate, generatedAt } = demoReport;
  const jobs = demoReport.jobs as DemoJob[];

  return (
    <div className="p-5 md:p-9 max-w-5xl mx-auto">
      <div className="flex flex-col space-y-7 md:space-y-9">
        <Link href="/" className="flex items-center gap-1 text-sm text-foreground tracking-tight hover:underline w-fit">
          <ArrowLeftIcon className="h-4 w-4" />
          Back to home
        </Link>

        <div className="flex flex-col gap-4 md:flex-row md:items-end md:justify-between">
          <div className="flex flex-col space-y-1">
            <h1 className="text-2xl md:text-3xl font-bold tracking-tight">Sample report</h1>
            <p className="text-foreground text-md md:text-lg tracking-tight">
              Real job posts from {generatedAt}, matched by our AI to a sample CV.
            </p>
          </div>
          <Link href="/dashboard">
            <Button className="cursor-pointer bg-[#3b82f6] hover:bg-[#2563eb] text-white tracking-tight text-md transition-colors duration-300">
              Try it with your CV
            </Button>
          </Link>
        </div>

        <Card className="border border-slate-500">
          <CardContent className="space-y-3">
            <div className="text-xl md:text-2xl font-semibold tracking-tight">{candidate.role}</div>
            <div className="text-sm text-foreground tracking-tight">
              {candidate.years_experience} years of experience • {candidate.location}
            </div>
            <p className="text-sm text-foreground tracking-tight">{candidate.summary}</p>
            <div className="flex flex-wrap gap-2">
              {candidate.skills.map((skill) => (
                <Badge key={skill} variant="secondary" className="text-sm tracking-tight border border-slate-500">
                  {skill}
                </Badge>
              ))}
            </div>
          </CardContent>
        </Card>

        {jobs.map(({ jobPost, matchScore, matchDetails }) => (
          <JobPostCardItem
            key={jobPost.id}
            jobPost={jobPost}
            isBlurred={false}
            matchScore={matchScore}
            matchDetails={matchDetails}
          />
        ))}
      </div>
    </div>
  );
}

export default DemoReport;
